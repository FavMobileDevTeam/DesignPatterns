// Снимок (Memento): Сохраняет и восстанавливает внутреннее состояние объекта без нарушения инкапсуляции.
// Команда (Command): Инкапсулирует действие (запрос) в объект, позволяя параметризировать клиентов разными запросами, ставить их в очередь, логировать и отменять.

// 2. Подход к отмене действий

// Снимок: Восстанавливает объект до предыдущего состояния, "возвращая в прошлое".
// Команда: Выполняет обратную операцию (часто с помощью метода undo()), которая компенсирует эффект команды.

// 3. Что хранится

// Снимок: Хранит полную копию состояния объекта в определенный момент времени.
// Команда: Хранит информацию о действии, которое нужно выполнить (и часто информацию для отмены).

