// Основные отличия
// 1. Структура коммуникации

// Посредник: Создает централизованную точку коммуникации ("многие-к-одному-к-многим"). Компоненты общаются друг с другом только через посредника.
// Наблюдатель: Создает децентрализованную структуру "один-ко-многим", где источник (субъект) уведомляет всех наблюдателей об изменениях.

// 2. Направление зависимостей

// Посредник: Компоненты знают о посреднике, а посредник знает обо всех компонентах. Компоненты не знают друг о друге.
// Наблюдатель: Субъект не знает конкретных классов наблюдателей, а работает только с их интерфейсом. Наблюдатели знают о субъекте.

// 3. Цель паттерна

// Посредник: Уменьшение связанности между множеством взаимодействующих объектов путем централизации их коммуникации.
// Наблюдатель: Обеспечение уведомления объектов об изменениях состояния другого объекта без тесной связи между ними.

// 4. Контроль взаимодействия

// Посредник: Явно контролирует и координирует взаимодействие между компонентами.
// Наблюдатель: Только информирует о изменениях, не контролируя, как наблюдатели реагируют.
